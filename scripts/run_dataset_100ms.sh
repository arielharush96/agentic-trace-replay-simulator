#!/usr/bin/env bash
# Run the dataset and generate the final OpenClaw resource time-series plots.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

TARGET_NODE="${TARGET_NODE:?TARGET_NODE is required}"
CORPUS_ROOT="${CORPUS_ROOT:-$ROOT/results/dataset-10/20260908T145713Z}"
RUN_STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
OUT_ROOT="${OUT_ROOT:-$ROOT/results/dataset-10-multiturn/$RUN_STAMP}"
KUBECONFIG="${KUBECONFIG:-$HOME/.kube/config}"
MOCK_CORPUS="$OUT_ROOT/mock-corpus.json"
export KUBECONFIG TARGET_NODE

oc get node "$TARGET_NODE" >/dev/null
mkdir -p "$OUT_ROOT"
exec > >(tee "$OUT_ROOT/run.log") 2>&1

STARTED_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
cat > "$OUT_ROOT/EXPERIMENT.md" <<EOF
# OpenClaw/OpenShell Dataset Experiment

- Started: $STARTED_AT
- Target node: $TARGET_NODE
- Corpus root: $CORPUS_ROOT
- Sampler interval: ${CGROUP_SAMPLE_INTERVAL_MS:-100} ms
- CPU source: cgroup-v2 100 ms sampler, cross-checked with exact-pod Prometheus/cAdvisor
- Memory source: cgroup-v2 memory.current, cross-checked with exact-pod Prometheus/cAdvisor
- Output: one directory per corpus under this directory
- Final plots: generated automatically under aggregate/
EOF
cat > "$OUT_ROOT/MATCHED_COMPARISON_STATUS.md" <<'EOF'
# Matched OpenShell Comparison

The matched incremental OpenShell-overhead plot is not generated by this
shell-only run. It requires a plain OpenClaw run using the same image, corpus,
agent configuration, and equal internal step count. The runner will not create
that plot from unmatched data.
EOF
oc get node "$TARGET_NODE" -o yaml > "$OUT_ROOT/target-node.yaml"
oc -n trace-replay get pods -o wide > "$OUT_ROOT/trace-replay-pods.txt"
oc -n openshell-tracesim get pods -o wide > "$OUT_ROOT/openshell-pods.txt"
if [ ! -s "$MOCK_CORPUS" ]; then
  PYTHONPATH=src python3 "$ROOT/scripts/merge_replay_corpora.py" \
    --root "$CORPUS_ROOT" \
    --out "$MOCK_CORPUS"
fi

first=1
total=0
for _corpus in "$CORPUS_ROOT"/*__*-corpus-turns/corpus.json; do total=$((total + 1)); done
index=0
for corpus in "$CORPUS_ROOT"/*__*-corpus-turns/corpus.json; do
  index=$((index + 1))
  task="${corpus%/corpus.json}"
  task="${task##*/}"
  echo "[dataset $index/$total] Starting $task"
  echo "[dataset $index/$total] Measuring OpenClaw gateway and OpenShell sandbox CPU/memory, traces, and per-turn latency"
  reset_mock=0
  [ "$first" -eq 1 ] && reset_mock=1
  CORPUS="$corpus" MOCK_CORPUS="$MOCK_CORPUS" RESET_MOCK="$reset_mock" OUT_DIR="$OUT_ROOT/$task" \
    bash "$ROOT/scripts/run_profiler_v2.sh"
  echo "[dataset $index/$total] Completed $task; remaining $((total - index))"
  first=0
done

echo "[postprocess] Regenerating per-corpus resource summaries and Mean/P50/P95 bar charts"
for task_dir in "$OUT_ROOT"/*__*-corpus-turns; do
  cgroup_dir="$task_dir/prometheus/cgroup"
  cgroup_files=("$cgroup_dir"/*.csv)
  if [ -e "${cgroup_files[0]}" ]; then
    PYTHONPATH=src python3 "$ROOT/scripts/resource_analysis_v3.py" \
      --samples "${cgroup_files[@]}" \
      --out "$task_dir/prometheus/cgroup-analysis"
    PYTHONPATH=src python3 "$ROOT/scripts/resource_analysis_v3.py" \
      --samples "${cgroup_files[@]}" \
      --edges "$task_dir/shell/mock_edges.jsonl" \
      --out "$task_dir/resource-study"
  fi
done

if [ "${RUN_MATCHED:-0}" = "1" ]; then
  echo "[matched 1/2] Running plain OpenClaw for all ten corpora"
  matched_total=0
  for _corpus in "$CORPUS_ROOT"/*__*-corpus-turns/corpus.json; do matched_total=$((matched_total + 1)); done
  matched_index=0
  for corpus in "$CORPUS_ROOT"/*__*-corpus-turns/corpus.json; do
    matched_index=$((matched_index + 1))
    task="${corpus%/corpus.json}"
    task="${task##*/}"
    echo "[matched 1/2] Plain OpenClaw $matched_index/$matched_total: $task"
    CORPUS="$corpus" OUT_DIR="$OUT_ROOT/$task/openclaw" RESET_MOCK=0 TARGET_NODE="$TARGET_NODE" \
      bash "$ROOT/scripts/run_matched_openclaw.sh"
  done
  echo "[matched 2/2] Validating equal internal step counts and generating the matched overhead plot"
  PYTHONPATH=src python3 -m trace_replay_sim.cli study-v3 \
    --root "$OUT_ROOT" \
    --out "$OUT_ROOT/studies-v3"
else
  echo "[matched] Skipped; set RUN_MATCHED=1 to generate the matched comparison"
fi

echo "[organize] Normalizing every corpus into plots-analysis, logs, data, and manifests"
for corpus in "$CORPUS_ROOT"/*__*-corpus-turns/corpus.json; do
  task="${corpus%/corpus.json}"
  task="${task##*/}"
  task_command="TARGET_NODE=$TARGET_NODE CORPUS=$corpus OUT_ROOT=$OUT_ROOT bash scripts/run_dataset_100ms.sh"
  PYTHONPATH=src python3 "$ROOT/scripts/organize_corpus_output.py" \
    --root "$ROOT" \
    --task "$OUT_ROOT/$task" \
    --corpus "$corpus" \
    --target-node "$TARGET_NODE" \
    --command "$task_command"
done

date -u +%Y-%m-%dT%H:%M:%SZ > "$OUT_ROOT/completed_at.txt"

PYTHONPATH=src python3 "$ROOT/scripts/aggregate_resource_analysis.py" \
  --root "$OUT_ROOT" \
  --out "$OUT_ROOT/aggregate"

echo "Dataset run and resource graph generation complete: $OUT_ROOT"
